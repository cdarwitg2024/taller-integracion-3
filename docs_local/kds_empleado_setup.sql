DO $$
DECLARE
  v_auth_id uuid;
  v_emp_id bigint;
  v_role_id bigint := (SELECT id FROM public.roles WHERE nombre = 'empleado');
BEGIN
  -- Si ya existe el auth user con ese email, no duplicar
  SELECT id INTO v_auth_id FROM auth.users WHERE email = 'empleado@cofeefast.cl';
  IF v_auth_id IS NULL THEN
    INSERT INTO auth.users (
      instance_id, id, aud, role, email,
      encrypted_password, email_confirmed_at,
      confirmation_token, recovery_token,
      email_change_token_new, email_change,
      email_change_token_current, email_change_confirm_status,
      reauthentication_token,
      is_sso_user, is_anonymous,
      raw_app_meta_data, raw_user_meta_data,
      created_at, updated_at
    )
    VALUES (
      '00000000-0000-0000-0000-000000000000',
      gen_random_uuid(),
      'authenticated', 'authenticated', 'empleado@cofeefast.cl',
      crypt('123456', gen_salt('bf')),
      now(),
      '', '',
      '', '',
      '', 0,
      '',
      false, false,
      '{"provider":"email","providers":["email"]}',
      '{}',
      now(), now()
    )
    RETURNING id INTO v_auth_id;

    INSERT INTO auth.identities (
      provider_id, user_id, identity_data, provider,
      last_sign_in_at, created_at, updated_at
    )
    VALUES (
      'empleado@cofeefast.cl', v_auth_id,
      jsonb_build_object('sub', v_auth_id::text, 'email', 'empleado@cofeefast.cl'),
      'email', now(), now(), now()
    );
  END IF;

  -- Enlazar/crear la fila public.usuarios con rol empleado
  SELECT id INTO v_emp_id FROM public.usuarios WHERE email = 'empleado@cofeefast.cl';
  IF v_emp_id IS NULL THEN
    INSERT INTO public.usuarios (rol_id, nombre, apellido, email, auth_user_id, activo)
    VALUES (v_role_id, 'Juan', 'Empleado', 'empleado@cofeefast.cl', v_auth_id, true);
  ELSE
    UPDATE public.usuarios
       SET rol_id = v_role_id, auth_user_id = v_auth_id, activo = true
     WHERE id = v_emp_id;
  END IF;
END $$;

