-- ---------------------------------------------------------------
-- 4) Regla de flujo (FR-31): no se pueden saltar estados
--    pendiente -> en_preparacion -> listo -> entregado.
--    Bloquea también los PATCH/REST directos.
-- ---------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.validar_transicion_estado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  viejo_estado text := OLD.estado;
  nuevo_estado text := NEW.estado;
BEGIN
  IF viejo_estado = 'preparando' THEN viejo_estado := 'en_preparacion'; END IF;
  IF nuevo_estado = 'preparando' THEN nuevo_estado := 'en_preparacion'; END IF;

  IF viejo_estado = nuevo_estado THEN
    RETURN NEW;
  END IF;

  IF NOT (
    (viejo_estado = 'pendiente' AND nuevo_estado IN ('en_preparacion', 'cancelado')) OR
    (viejo_estado = 'en_preparacion' AND nuevo_estado IN ('listo', 'cancelado')) OR
    (viejo_estado = 'listo' AND nuevo_estado = 'entregado')
  ) THEN
    RAISE EXCEPTION 'Transición inválida de estado: % -> %', OLD.estado, NEW.estado;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_transicion_estado ON public.pedidos;
CREATE TRIGGER trg_validar_transicion_estado
  BEFORE UPDATE OF estado ON public.pedidos
  FOR EACH ROW EXECUTE FUNCTION public.validar_transicion_estado();

SELECT 'SETUP OK' AS estado;