CREATE TABLE public.roles (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre   text NOT NULL UNIQUE,
  activo   boolean NOT NULL DEFAULT true
);

CREATE TABLE public.usuarios (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol_id          bigint NOT NULL REFERENCES public.roles (id),
  nombre          text NOT NULL,
  apellido        text NOT NULL DEFAULT '',
  email           text UNIQUE,
  telefono        text,
  foto_url        text,
  password_hash   text,
  auth_user_id    uuid UNIQUE,
  activo          boolean NOT NULL DEFAULT true,
  ultima_conexion timestamptz,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz
);

CREATE TABLE public.cafeterias (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id     bigint,
  nombre        text NOT NULL,
  descripcion   text,
  hora_apertura time,
  hora_cierre   time,
  activa        boolean NOT NULL DEFAULT true
);

CREATE TABLE public.productos (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cafeteria_id bigint NOT NULL REFERENCES public.cafeterias (id),
  categoria_id bigint,
  nombre       text NOT NULL,
  descripcion  text,
  precio       numeric(12,2) NOT NULL DEFAULT 0,
  stock        integer NOT NULL DEFAULT 0,
  activo       boolean NOT NULL DEFAULT true
);

CREATE TABLE public.pedidos (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cafeteria_id            bigint NOT NULL REFERENCES public.cafeterias (id),
  usuario_id              bigint REFERENCES public.usuarios (id),
  codigo_retiro_diario    text,
  estado                  text NOT NULL DEFAULT 'pendiente',
  total                   numeric(12,2) NOT NULL DEFAULT 0,
  qr_token                text UNIQUE,
  hora_retiro             timestamptz,
  creado_en               timestamptz NOT NULL DEFAULT now(),
  inicio_preparacion_en   timestamptz,
  listo_en                timestamptz,
  entregado_en            timestamptz,
  completado_en           timestamptz,
  cancelado_en            timestamptz
);

CREATE TABLE public.detalles_pedido (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id       bigint NOT NULL REFERENCES public.pedidos (id),
  producto_id     bigint REFERENCES public.productos (id),
  cantidad        integer NOT NULL DEFAULT 1,
  precio_unitario numeric(12,2) NOT NULL DEFAULT 0,
  modificaciones  text
);

